/**
 * 起草提示词：从人设档案里挑出真正有用的几段，再拼系统提示。
 * 规则：按 `## ` 切段，跳过「十、」「十一、」和维护/来源/隐私类小节，
 * 其余（实测画像、我是谁、立场、说话方式、套路、场景、例句、自动归纳）全部带上。
 * 这样档案可以自由排版、加新段，只要不标成「不喂给模型」就会被读到。
 */

const SKIP_SECTION = /^(十、|十一、)|维护|来源|隐私/

/** 人设摘要：除维护/隐私外的全部小节，最多 limit 字 */
export function personaExcerpt(raw, limit = 6500) {
  const text = String(raw || '').trim()
  if (!text) return ''
  const parts = text.split(/^##\s+/m)
  if (parts.length < 2) return text.slice(0, limit)
  const kept = []
  for (const block of parts.slice(1)) {
    const title = block.split('\n')[0].trim()
    if (SKIP_SECTION.test(title)) continue
    kept.push(`## ${block.trim()}`)
  }
  return kept.join('\n\n').slice(0, limit)
}

